/**
 * Embeds the Mova mascot SVGs (assets/illustrations/mova/*.svg, the editable
 * source of truth) into a TypeScript module so the app can render them as
 * vectors on web, iOS and Android with react-native-svg.
 * Run: npm run mascot:generate
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '../../../assets/illustrations/mova');
const moods = ['welcome', 'fitness', 'planning', 'focus', 'hydration', 'celebration', 'rest', 'checklist', 'thinking', 'nutrition', 'calm', 'phone'];

const out = {};
for (const mood of moods) {
  out[mood] = readFileSync(join(dir, `mova-bubble-${mood}.svg`), 'utf8').replace(/\s*\n\s*/g, ' ').replace(/>\s+</g, '><').trim();
}
writeFileSync(
  join(here, '../src/components/mascotData.generated.ts'),
  `// GENERATED by scripts/generate-mascot-svgs.mjs from assets/illustrations/mova/*.svg. Do not edit.\nexport const MASCOT_SVG = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log(`Wrote ${moods.length} mascot SVGs.`);
