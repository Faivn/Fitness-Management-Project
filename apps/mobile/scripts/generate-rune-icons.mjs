/**
 * Extracts the few Rune Icons (https://www.runeicons.com, Apache-2.0) that Mova
 * uses into src/components/runeIconData.generated.ts, so the app bundles ~20
 * small SVG snippets instead of the whole 1.8 MB icon set.
 *
 * Run: npm run icons:generate -w mobile   (requires the `runeicons` devDependency)
 * Only the "normal" (outline, currentColor) style is used, so icons can be tinted.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIconById, ICONS } from 'runeicons';

// short name used in the app -> Rune icon name suffix
const WANTED = {
  chat: 'message-circle',
  settings: 'settings',
  plus: 'plus',
  minus: 'minus',
  close: 'x',
  check: 'check',
  'chevron-left': 'chevron-left',
  'chevron-right': 'chevron-right',
  'chevron-down': 'chevron-down',
  'chevron-up': 'chevron-up',
  'arrow-right': 'arrow-right',
  'arrow-up-right': 'arrow-up-right',
  overview: 'house',
  workouts: 'activity',
  schedule: 'calendar',
  meals: 'shopping-basket',
  history: 'history',
  clock: 'clock',
  alarm: 'alarm-clock',
  play: 'play',
  sparkles: 'sparkles',
  'circle-check': 'circle-check',
  'circle-x': 'circle-x',
  'circle-alert': 'circle-alert',
  'circle-dot': 'circle-dot',
  'circle-question': 'circle-question-mark',
  bolt: 'zap',
};

const out = {};
for (const [name, suffix] of Object.entries(WANTED)) {
  const matches = ICONS.filter((i) => i.variants.normal && (i.id === suffix || i.id.endsWith(`-${suffix}`)));
  // Prefer an exact `<category>-<suffix>` id; otherwise require a single match.
  const exact = matches.filter((i) => i.id.split('-').slice(1).join('-') === suffix);
  const pick = exact.length === 1 ? exact[0] : matches.length === 1 ? matches[0] : null;
  if (!pick) throw new Error(`Rune icon "${suffix}" for "${name}" is ambiguous or missing: ${matches.map((m) => m.id).join(', ') || 'none'}`);
  const v = getIconById(pick.id).variants.normal;
  out[name] = { id: pick.id, viewBox: v.viewBox, markup: v.markup.replace(/\r?\n/g, '') };
}

const here = dirname(fileURLToPath(import.meta.url));
const file = join(here, '../src/components/runeIconData.generated.ts');
writeFileSync(
  file,
  `// GENERATED by scripts/generate-rune-icons.mjs — do not edit.
// Icons from RuneIcons (https://www.runeicons.com), Apache-2.0. "normal" style, tinted via currentColor.
export const RUNE_ICONS = ${JSON.stringify(out, null, 2)} as const;

export type RuneIconName = keyof typeof RUNE_ICONS;
`,
);
console.log(`Wrote ${Object.keys(out).length} icons to ${file}`);
